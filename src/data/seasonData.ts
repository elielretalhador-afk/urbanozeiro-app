export function getSeasonStatusBadge(status: SeasonStatus): {
  label: string;
  bg: string;
  text: string;
  border: string;
} {
  switch (status) {
    case 'ACTIVE':
      return {
        label: 'ATIVA',
        bg: 'bg-yellow-500/20',
        text: 'text-yellow-300',
        border: 'border-yellow-400/40',
      };
    case 'ENDING_SOON':
      return {
        label: 'TERMINA EM BREVE',
        bg: 'bg-amber-500/20',
        text: 'text-amber-300',
        border: 'border-amber-400/40',
      };
    case 'UPCOMING':
      return {
        label: 'EM BREVE',
        bg: 'bg-cyan-500/20',
        text: 'text-cyan-300',
        border: 'border-cyan-400/40',
      };
    case 'FINISHED':
      return {
        label: 'FINALIZADA',
        bg: 'bg-slate-500/20',
        text: 'text-slate-300',
        border: 'border-slate-400/40',
      };
    case 'ARCHIVED':
      return {
        label: 'ARQUIVADA',
        bg: 'bg-zinc-500/20',
        text: 'text-zinc-400',
        border: 'border-zinc-500/40',
      };
    default:
      return {
        label: 'TEMPORADA',
        bg: 'bg-slate-500/20',
        text: 'text-slate-300',
        border: 'border-slate-400/40',
      };
  }
}
